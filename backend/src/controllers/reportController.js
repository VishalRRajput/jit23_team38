function escapePdf(text) {
  return String(text || '').replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function generatePdfBuffer({ title, subtitle, headers, rows }) {
  const pageWidth = 612; // Standard Letter
  const pageHeight = 792;
  const margin = 36;
  const usableWidth = pageWidth - margin * 2;
  const rowHeight = 20;
  const rowsPerPage = 26;

  const totalPages = Math.max(1, Math.ceil(rows.length / rowsPerPage));
  const colWidth = usableWidth / headers.length;

  let pageObjNums = [];
  let contentObjNums = [];

  let currentObj = 5;
  for (let p = 0; p < totalPages; p++) {
    pageObjNums.push(currentObj++);
    contentObjNums.push(currentObj++);
  }

  let pdf = '%PDF-1.4\n';
  let offsets = [];

  function recordOffset() {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
  }

  // Obj 1: Catalog
  recordOffset();
  pdf += '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n';

  // Obj 2: Pages
  recordOffset();
  pdf += '2 0 obj\n<< /Type /Pages /Kids [' + pageObjNums.map(n => n + ' 0 R').join(' ') + '] /Count ' + totalPages + ' >>\nendobj\n';

  // Obj 3: Font Regular
  recordOffset();
  pdf += '3 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>\nendobj\n';

  // Obj 4: Font Bold
  recordOffset();
  pdf += '4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>\nendobj\n';

  for (let p = 0; p < totalPages; p++) {
    const pageNum = p + 1;
    const pageRows = rows.slice(p * rowsPerPage, (p + 1) * rowsPerPage);

    let stream = '';
    stream += 'q\n';

    // Header banner dark navy
    stream += '0.12 0.16 0.22 rg\n';
    stream += margin + ' ' + (pageHeight - margin - 46) + ' ' + usableWidth + ' 46 re f\n';

    // Title
    stream += 'BT /F2 15 Tf 1 1 1 rg ' + (margin + 12) + ' ' + (pageHeight - margin - 24) + ' Td (' + escapePdf(title) + ') Tj ET\n';
    // Subtitle
    stream += 'BT /F1 8.5 Tf 0.8 0.85 0.9 rg ' + (margin + 12) + ' ' + (pageHeight - margin - 38) + ' Td (' + escapePdf(subtitle + ' | Page ' + pageNum + ' of ' + totalPages) + ') Tj ET\n';

    // Table Header
    const tableTop = pageHeight - margin - 66;
    stream += '0.24 0.28 0.36 rg\n';
    stream += margin + ' ' + (tableTop - 18) + ' ' + usableWidth + ' 18 re f\n';

    for (let c = 0; c < headers.length; c++) {
      const x = margin + c * colWidth + 5;
      const y = tableTop - 13;
      stream += 'BT /F2 8.5 Tf 1 1 1 rg ' + x + ' ' + y + ' Td (' + escapePdf(headers[c]) + ') Tj ET\n';
    }

    // Table Rows
    let currentY = tableTop - 18;
    for (let r = 0; r < pageRows.length; r++) {
      const row = pageRows[r];
      if (r % 2 === 0) {
        stream += '0.96 0.97 0.98 rg\n';
        stream += margin + ' ' + (currentY - rowHeight) + ' ' + usableWidth + ' ' + rowHeight + ' re f\n';
      }
      // Row bottom border
      stream += '0.88 0.90 0.92 RG 0.5 w\n';
      stream += margin + ' ' + (currentY - rowHeight) + ' m ' + (margin + usableWidth) + ' ' + (currentY - rowHeight) + ' l S\n';

      for (let c = 0; c < headers.length; c++) {
        const val = String(row[c] !== undefined && row[c] !== null ? row[c] : '');
        const x = margin + c * colWidth + 5;
        const y = currentY - 14;

        const maxChars = Math.floor(colWidth / 5.5);
        const displayVal = val.length > maxChars ? val.substring(0, maxChars - 2) + '..' : val;

        stream += 'BT /F1 8 Tf 0.15 0.18 0.22 rg ' + x + ' ' + y + ' Td (' + escapePdf(displayVal) + ') Tj ET\n';
      }
      currentY -= rowHeight;
    }

    // Footer
    stream += 'BT /F1 7.5 Tf 0.5 0.5 0.5 rg ' + margin + ' ' + (margin - 16) + ' Td (Generated by Employee Tracking System | Confidential) Tj ET\n';
    stream += 'Q\n';

    const streamLength = Buffer.byteLength(stream, 'latin1');

    // Obj Page
    recordOffset();
    pdf += pageObjNums[p] + ' 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ' + pageWidth + ' ' + pageHeight + '] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ' + contentObjNums[p] + ' 0 R >>\nendobj\n';

    // Obj Content
    recordOffset();
    pdf += contentObjNums[p] + ' 0 obj\n<< /Length ' + streamLength + ' >>\nstream\n' + stream + '\nendstream\nendobj\n';
  }

  // xref
  const startXref = Buffer.byteLength(pdf, 'latin1');
  const totalObjects = offsets.length + 1;
  pdf += 'xref\n0 ' + totalObjects + '\n0000000000 65535 f \n';
  for (let o = 0; o < offsets.length; o++) {
    pdf += String(offsets[o]).padStart(10, '0') + ' 00000 n \n';
  }

  pdf += 'trailer\n<< /Size ' + totalObjects + ' /Root 1 0 R >>\nstartxref\n' + startXref + '\n%%EOF';

  return Buffer.from(pdf, 'latin1');
}

export const getReportsList = async (req, res) => {
  try {
    const reports = await Report.find().sort({ createdAt: -1 });
    res.json({ success: true, count: reports.length, reports });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const generateReport = async (req, res) => {
  try {
    const { title, reportType, fileFormat = 'PDF' } = req.body;

    let recordCount = 0;
    if (reportType === 'ATTENDANCE') {
      recordCount = await Attendance.countDocuments();
    } else if (reportType === 'GEOFENCE_LOGS') {
      recordCount = await GeofenceLog.countDocuments();
    } else {
      recordCount = await Location.countDocuments();
    }

    const typeKey = reportType.toLowerCase().replace('_history', '').replace('_logs', '');
    const ext = fileFormat.toLowerCase() === 'excel' ? 'xls' : fileFormat.toLowerCase();

    const report = await Report.create({
      title: title || `${reportType} Enterprise Report`,
      reportType,
      fileFormat,
      generatedBy: req.user?.name || 'System Admin',
      recordCount,
      downloadUrl: `/api/reports/download/${typeKey}.${ext}`
    });

    res.status(201).json({ success: true, message: 'Report generated successfully', report });
  } catch (error) {
    res.status(500).json({ success: false, message: error.message });
  }
};

export const exportReportData = async (req, res) => {
  try {
    const { type, format } = req.params;
    const typeNorm = (type || '').toLowerCase().replace('_history', '').replace('_logs', '');
    const formatNorm = (format || '').toLowerCase();

    let title = 'Enterprise Report';
    let headers = [];
    let rows = [];
    let rawRecords = [];

    if (typeNorm === 'attendance') {
      title = 'Employee Attendance Summary Report';
      headers = ['Employee ID', 'Name', 'Department', 'Date', 'Check-In', 'Check-Out', 'Working Hours', 'Status'];
      const records = await Attendance.find().sort({ date: -1, createdAt: -1 }).limit(100);
      const employees = await Employee.find();
      const empMap = {};
      employees.forEach(e => { empMap[e.employeeId] = e; });

      rows = records.map(r => {
        const emp = empMap[r.employeeId] || {};
        return [
          r.employeeId,
          emp.name || 'Unknown',
          emp.department || '--',
          r.date,
          r.checkInTime ? new Date(r.checkInTime).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) : '--',
          r.checkOutTime ? new Date(r.checkOutTime).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }) : (r.checkInTime ? 'Checked In' : '--'),
          r.workingHours ? `${r.workingHours} hrs` : '--',
          r.status || 'Absent'
        ];
      });
      rawRecords = records;

    } else if (typeNorm === 'geofence') {
      title = 'Geofence Entry & Exit Audit Report';
      headers = ['Timestamp', 'Employee ID', 'Device ID', 'Event Type', 'Method', 'Duration'];
      const records = await GeofenceLog.find().sort({ timestamp: -1 }).limit(100);

      rows = records.map(r => [
        new Date(r.timestamp).toLocaleString(),
        r.employeeId,
        r.deviceId || '--',
        r.eventType,
        r.verificationMethod || 'GPS',
        r.durationMinutes ? `${r.durationMinutes} mins` : '--'
      ]);
      rawRecords = records;

    } else {
      // Movement / Location
      title = 'Movement & Telemetry History Report';
      headers = ['Timestamp', 'Employee ID', 'Latitude', 'Longitude', 'Speed (km/h)', 'Battery (%)', 'Verification'];
      const records = await Location.find().sort({ timestamp: -1 }).limit(100);

      rows = records.map(r => [
        new Date(r.timestamp).toLocaleString(),
        r.employeeId,
        r.latitude ? r.latitude.toFixed(6) : '--',
        r.longitude ? r.longitude.toFixed(6) : '--',
        r.speed ? r.speed.toFixed(1) : '0',
        `${r.battery || 100}%`,
        r.isIndoor ? 'INDOOR' : (r.verificationMethod || 'GPS')
      ]);
      rawRecords = records;
    }

    const timestamp = Date.now();

    // 1. CSV Format
    if (formatNorm === 'csv') {
      const escapeCsv = (val) => `"${String(val ?? '').replace(/"/g, '""')}"`;
      const csv = '\uFEFF' + [
        headers.map(escapeCsv).join(','),
        ...rows.map(r => r.map(escapeCsv).join(','))
      ].join('\r\n');

      res.setHeader('Content-Type', 'text/csv; charset=utf-8');
      res.setHeader('Content-Disposition', `attachment; filename=${typeNorm}_report_${timestamp}.csv`);
      return res.send(csv);
    }

    // 2. Excel Format (.xls)
    if (formatNorm === 'excel' || formatNorm === 'xls') {
      const html = `
        <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
        <head>
          <meta charset="utf-8">
          <!--[if gte mso 9]><xml><x:ExcelWorkbook><x:ExcelWorksheets><x:ExcelWorksheet><x:Name>Sheet1</x:Name><x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions></x:ExcelWorksheet></x:ExcelWorksheets></x:ExcelWorkbook></xml><![endif]-->
          <style>
            body { font-family: Arial, sans-serif; }
            th { background-color: #1e293b; color: #ffffff; font-weight: bold; padding: 8px 12px; border: 1px solid #475569; text-align: left; }
            td { padding: 6px 12px; border: 1px solid #cbd5e1; font-size: 11px; }
            tr:nth-child(even) td { background-color: #f8fafc; }
          </style>
        </head>
        <body>
          <h2>${title}</h2>
          <p>Generated: ${new Date().toLocaleString()} | Total Records: ${rows.length}</p>
          <table>
            <thead><tr>${headers.map(h => `<th>${h}</th>`).join('')}</tr></thead>
            <tbody>
              ${rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('')}
            </tbody>
          </table>
        </body>
        </html>
      `;

      res.setHeader('Content-Type', 'application/vnd.ms-excel; charset=utf-8');
      res.setHeader('Content-Disposition', `attachment; filename=${typeNorm}_report_${timestamp}.xls`);
      return res.send(html);
    }

    // 3. PDF Format
    if (formatNorm === 'pdf') {
      const pdfBuffer = generatePdfBuffer({
        title,
        subtitle: `Generated: ${new Date().toLocaleString()} | Total Records: ${rows.length}`,
        headers,
        rows
      });

      res.setHeader('Content-Type', 'application/pdf');
      res.setHeader('Content-Disposition', `attachment; filename=${typeNorm}_report_${timestamp}.pdf`);
      return res.send(pdfBuffer);
    }

    // 4. Default JSON fallback
    res.setHeader('Content-Type', 'application/json');
    res.setHeader('Content-Disposition', `attachment; filename=${typeNorm}_report_${timestamp}.json`);
    res.json(rawRecords);

  } catch (error) {
    console.error('[Export Report Error]:', error);
    res.status(500).json({ success: false, message: error.message });
  }
};
